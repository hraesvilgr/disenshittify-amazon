# Trains the English letter-pair model used to spot gibberish brand names.
# Uses whatever English text is on this machine (licenses, Python stdlib, /usr/share/doc).
# Run: python3 tools/train_bigrams.py
import os, re, math, json, collections
words = collections.Counter()
roots = ['/usr/share/common-licenses', '/usr/lib/python3.13', '/usr/share/doc']
for root in roots:
    for dp, dn, fn in os.walk(root):
        for f in fn:
            p = os.path.join(dp, f)
            if not (f.endswith(('.py','.txt','.md','')) or 'licenses' in dp): continue
            try:
                if os.path.getsize(p) > 2_000_000: continue
                t = open(p, encoding='utf-8', errors='ignore').read()
            except Exception: continue
            for w in re.findall(r'(?<![A-Za-z_])[A-Za-z]{3,}(?![A-Za-z_])', t):
                if w.isupper() or not w[1:].islower() and not w.islower(): continue
                words[w.lower()] += 1
print('distinct words', len(words))
# type-based counts, damped by frequency
big = collections.Counter(); uni = collections.Counter()
for w, c in words.items():
    if c < 3: continue  # drop noise/identifiers
    wt = 1 + math.log(c)
    s = '^' + w + '$'
    for a, b in zip(s, s[1:]):
        big[a+b] += wt; uni[a] += wt
alpha = '^abcdefghijklmnopqrstuvwxyz$'
table = {}
for a in alpha[:-1]:
    tot = uni[a] + 0.5*27
    for b in alpha[1:]:
        table[a+b] = round(math.log((big[a+b] + 0.5)/tot), 2)
rows = {a: [table[a+b] for b in alpha[1:]] for a in alpha[:-1]}
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'bigrams.js')
open(out, 'w').write(
    "// Letter-pair log probabilities for English words (generated by tools/train_bigrams.py).\n"
    "// Row = first letter ('^' = word start); columns = 'abcdefghijklmnopqrstuvwxyz$' ('$' = word end).\n"
    "var DSA_BIGRAMS = " + json.dumps(rows, separators=(',', ':')) + ";\n"
    "if (typeof module !== 'undefined') module.exports = DSA_BIGRAMS;\n")
print('wrote', out)
def score(w):
    s = '^' + re.sub('[^a-z]','',w.lower()) + '$'
    lp = [table[a+b] for a,b in zip(s,s[1:])]
    return sum(lp)/len(lp), min(lp)
for w in 'Pavsrmy Gicyiit HOOMIL Tiawudi Coukre Yupjlia AYCCNH KITESSENSU AMAGABELI ZOOFOX CoguZed ABuff GRIDMANN CHEFMADE Cuisinart Farberware Calphalon Wilton Nordic Lodge OXO Anolon Ninja Baguette Sourdough Kitchen Pyrex Hamilton Beach Zojirushi Breville Keurig Rubbermaid Tupperware Vremi Utopia Amazon Basics Hiware Sweejar Lekue Bellemain Gorilla Grip Mueller Ecozoi Joseph Simple Modern'.split():
    a, m = score(w); print(f'{w:12s} avg {a:6.2f} min {m:6.2f}')
